"""OnboardingPort: the only way the agent touches its own onboarding business data -- employee
cases, tasks, sessions, RSVPs, invitations, client configuration, communication drafts and
notification records.

This is the agent's system of record (it creates and updates every row), not an integration with
an external system, which is why it lives here rather than under connectors/. Implementations:
  - SqliteOnboardingRepository (sub_agent.persistence) -- the persistent store, used whenever
    HR_AGENT_PERSIST=1 and required when HR_AGENT_ENV=production. Single-node only (see that module).
  - MockOnboarding (sub_agent.fakes) -- in-memory, for tests and local development.
Both are run through the same contract tests (tests/test_onboarding_repository.py).

Contract every implementation must honour (the services, tool registry and tests rely on it):
  - Tenant isolation: get_task/get_session/get_communication_draft take an optional `client_id`;
    when given, a record owned by another client raises TenantMismatchError (a PermissionError).
    OnboardingToolRegistry relies on this for session/draft access.
  - Not-found lookups raise KeyError.
  - Uniqueness: one non-cancelled task per (employee, task_type); one non-cancelled session per
    (employee, session_type, scheduled_start); one case per employee -- each violation raises its
    Duplicate*Error.
  - record_participant_response upserts by (session, participant) with the given responded_at
    (the provider's timestamp) or the current time, atomically and newest-wins: a response older
    than the one already stored is not written, and the stored (newer) response is returned, so
    out-of-order deliveries can never roll an RSVP back.
  - Operation records (idempotency) are unique by key; save_operation upserts by key.
  - Every returned model is a copy; callers can never mutate stored state by reference.
"""

from __future__ import annotations

from datetime import datetime
from typing import Protocol, runtime_checkable

from sub_agent.models import (BuddyCandidate, CaseStatus, ClientConfig, CommunicationDraft,
                              CommunicationStatus, Invitation, InvitationStatus, Notification, OnboardingRecord,
                              OnboardingSession, OnboardingTask, OperationRecord, ParticipantResponse,
                              ResponseStatus, SessionStatus, TaskStatus)


class OnboardingPort(Protocol):
    # ---- employee records
    def get_onboarding_record(self, employee_id: str) -> OnboardingRecord: ...
    def list_onboarding_records(self, *, client_id: str | None = None) -> list[OnboardingRecord]: ...
    def create_onboarding_case(self, record: OnboardingRecord) -> OnboardingRecord: ...
    def update_case_status(self, employee_id: str, status: CaseStatus) -> OnboardingRecord: ...
    def list_buddy_candidates(self, client_id: str) -> list[BuddyCandidate]: ...
    def assign_buddy(self, employee_id: str, buddy_id: str) -> OnboardingRecord: ...
    def record_notification(self, employee_id: str, recipient_id: str, kind: str, **detail: object) -> Notification: ...
    def list_notifications(self, employee_id: str) -> list[Notification]: ...

    # ---- tasks
    def create_task(self, task: OnboardingTask) -> OnboardingTask: ...
    def get_task(self, task_id: str, *, client_id: str | None = None) -> OnboardingTask: ...
    def list_tasks(self, employee_id: str) -> list[OnboardingTask]: ...
    def update_task_status(self, task_id: str, status: TaskStatus) -> OnboardingTask: ...

    # ---- sessions
    def create_session(self, session: OnboardingSession) -> OnboardingSession: ...
    def get_session(self, session_id: str, *, client_id: str | None = None) -> OnboardingSession: ...
    def list_sessions(self, employee_id: str) -> list[OnboardingSession]: ...
    def update_session_status(self, session_id: str, status: SessionStatus) -> OnboardingSession: ...
    def record_participant_response(self, session_id: str, participant_id: str, response: ResponseStatus, *,
                                    responded_at: datetime | None = None) -> ParticipantResponse: ...
    def list_participant_responses(self, session_id: str) -> list[ParticipantResponse]: ...
    def record_invitation(self, session_id: str, participant_id: str,
                          status: InvitationStatus) -> Invitation: ...
    def update_invitation_status(self, invitation_id: str, status: InvitationStatus) -> Invitation: ...
    def list_invitations(self, session_id: str) -> list[Invitation]: ...

    # ---- client configuration
    def get_client_config(self, client_id: str) -> ClientConfig: ...

    # ---- communication drafts
    def create_communication_draft(self, draft: CommunicationDraft) -> CommunicationDraft: ...
    def get_communication_draft(self, draft_id: str, *, client_id: str | None = None) -> CommunicationDraft: ...
    def list_communication_drafts(self, employee_id: str) -> list[CommunicationDraft]: ...
    def update_communication_status(self, draft_id: str, status: CommunicationStatus) -> CommunicationDraft: ...

    # ---- idempotency records for external side effects
    def get_operation(self, key: str) -> OperationRecord | None: ...
    def save_operation(self, record: OperationRecord) -> OperationRecord: ...
    def list_operations(self, *, client_id: str | None = None,
                        statuses: tuple[str, ...] = ()) -> list[OperationRecord]: ...


@runtime_checkable
class BuddyAssignmentLedger(Protocol):
    """Optional capability: a repository that keeps the buddy PROPOSAL as a record of its own (supabase
    mode: buddy_assignments, status PROPOSED with the matching criteria). The local fakes do not; for
    them the proposal lives only in its HITL approval item, exactly as before."""

    def record_buddy_proposal(self, employee_id: str, buddy_id: str, *, approval_id: str, match_score: float,
                              same_team: bool) -> None: ...
    def release_buddy_proposal(self, employee_id: str, buddy_id: str) -> None: ...