"""Welcome communication drafting: approved per-client templates + deterministic fact
substitution + a short LLM-written personal note, submitted through the real HITLInbox approval
mechanism (hr_onboarding_common.platform.hitl) -- the same approval primitive used everywhere
else in the harness, not a bespoke onboarding-only approval status.

Every fact in the draft (name, role, start date, confirmed session time, buddy) is inserted by
code from OnboardingRecord/OnboardingSession -- never generated by the model -- so there is no way
for an LLM to invent or mis-state a date. The model's only contribution is a short personal note,
which is itself content-checked (no pay figures, no protected-attribute terms) before being kept;
if it fails, the note is dropped and the rest of the (code-authored) draft stands on its own. The
note's instructions are the `onboarding-welcome-writer` skill (context_layer/skills).

Delivery is not here: an approved draft is sent exactly once by OnboardingToolRegistry.
send_welcome_email, which sends the HITL-approved content (including HR's edits) through
NotificationPort and marks the draft SENT.
"""

from __future__ import annotations

from string import Formatter

from pydantic import BaseModel

from connectors.notifications.base import NotificationChannel
from context_layer.skills import load_skill
from hr_onboarding_common.contracts import new_id
from hr_onboarding_common.llm import LLMClient, ModelTier, input_block
from hr_onboarding_common.platform.audit import AuditLog
from hr_onboarding_common.platform.guardrails import detect_pay_figures, scan_protected_terms
from hr_onboarding_common.platform.hitl import ApprovalItem, Decision, HITLInbox
from sub_agent.models import (ClientConfig, CommunicationDraft, CommunicationStatus, InvalidClientConfigError,
                              MessageTemplate, MissingClientConfigError, OnboardingRecord, SessionStatus,
                              UnsupportedLanguageError)
from sub_agent.repository import OnboardingPort

AGENT_ID = "employee-onboarding"
GATE = "comms_approval"
NOTE_SKILL = load_skill("onboarding-welcome-writer")
# The facts draft_welcome_communication fills into a template. Any other placeholder cannot be filled.
TEMPLATE_FIELDS = frozenset({"full_name", "role_title", "start_date", "sender_name"})


class UnknownTemplateError(InvalidClientConfigError):
    """No template with this id in this language (a KeyError, as before)."""


class PersonalNoteOutput(BaseModel):
    personal_note: str


def client_config_for(port: OnboardingPort, client_id: str) -> ClientConfig:
    """The tenant's own ClientConfig -- looked up by the record's client_id, never another's."""
    try:
        return port.get_client_config(client_id)
    except KeyError:
        raise MissingClientConfigError("no welcome configuration (languages, branding, templates) is set up "
                                       "for this client") from None


def validate_template(template: MessageTemplate, *, template_id: str) -> None:
    """A template must have a subject and body, a supported channel, and only placeholders the
    drafting code fills (TEMPLATE_FIELDS). Checked before anything is drafted, so a bad template
    fails with a clear reason instead of a KeyError from str.format."""
    where = f"template '{template_id}' ({template.language})"
    if not template.subject.strip() or not template.body.strip():
        raise InvalidClientConfigError(f"{where} has an empty subject or body")
    if template.channel not in {c.value for c in NotificationChannel}:
        raise InvalidClientConfigError(f"{where} uses an unsupported channel '{template.channel}'")
    try:
        names = {name for text in (template.subject, template.body)
                 for _, name, _, _ in Formatter().parse(text) if name is not None}
    except ValueError:
        raise InvalidClientConfigError(f"{where} has malformed placeholder braces") from None
    unknown = sorted(n or "{}" for n in names if n not in TEMPLATE_FIELDS)
    if unknown:
        raise InvalidClientConfigError(f"{where} uses placeholder(s) the drafting code does not fill: "
                                       f"{', '.join(unknown)} (allowed: {', '.join(sorted(TEMPLATE_FIELDS))})")


def select_template(client: ClientConfig, *, template_id: str, language: str) -> MessageTemplate:
    """Language gate first (a disabled language is rejected before a template is even looked up),
    then template existence, then that the template actually exists in the requested language,
    then that it can be filled (validate_template)."""
    if language not in client.enabled_languages:
        raise UnsupportedLanguageError(f"language '{language}' is not enabled for {client.client_id} "
                                       f"(enabled: {client.enabled_languages})")
    template = client.templates.get(template_id)
    if template is None or template.language != language:
        raise UnknownTemplateError(f"no '{language}' version of template '{template_id}' is configured "
                                   f"for {client.client_id}")
    validate_template(template, template_id=template_id)
    return template


def _confirmed_session_line(port: OnboardingPort, employee_id: str) -> str:
    """Only a CONFIRMED session may be stated as a fact; scheduled-but-unconfirmed sessions are
    never mentioned as if they were settled."""
    confirmed = [s for s in port.list_sessions(employee_id) if s.status == SessionStatus.CONFIRMED]
    if not confirmed:
        return ""
    first = sorted(confirmed, key=lambda s: s.scheduled_start)[0]
    label = first.session_type.value.replace("_", " ")
    return f"Your {label} is confirmed for {first.scheduled_start.strftime('%A, %d %B %Y at %H:%M')}."


def draft_welcome_communication(port: OnboardingPort, llm: LLMClient, hitl: HITLInbox, audit: AuditLog, *,
                                employee_id: str, template_id: str, language: str,
                                workflow_instance: str) -> tuple[CommunicationDraft, ApprovalItem]:
    record: OnboardingRecord = port.get_onboarding_record(employee_id)  # KeyError if unknown
    client = client_config_for(port, record.client_id)  # MissingClientConfigError
    template = select_template(client, template_id=template_id, language=language)

    facts = {"full_name": record.full_name, "role_title": record.role_title,
            "start_date": record.start_date.isoformat(), "sender_name": client.branding.sender_name}
    subject = template.subject.format(**facts)
    body = template.body.format(**facts)

    session_line = _confirmed_session_line(port, employee_id)
    if session_line:
        body += "\n\n" + session_line
    if record.buddy_id:
        body += f"\n\nYour onboarding buddy is {record.buddy_id}."

    note_result: PersonalNoteOutput = llm.structured(
        task="onboarding.welcome_note", tier=ModelTier.FAST, schema=PersonalNoteOutput,
        system=NOTE_SKILL.instructions,
        user=input_block({"full_name": record.full_name, "role_title": record.role_title}), max_tokens=300)
    note = note_result.personal_note.strip()
    if detect_pay_figures(note) or scan_protected_terms(note):
        audit.record("welcome.note_dropped", agent=AGENT_ID, subject_id=employee_id,
                     reason="content_check_failed")
    else:
        body += "\n\n" + note

    draft = port.create_communication_draft(CommunicationDraft(
        employee_id=employee_id, client_id=record.client_id, template_id=template_id, language=language,
        subject=subject, body=body))

    item = hitl.submit(ApprovalItem(
        gate=GATE, approver_role="hr_admin", workflow="employee-onboarding", workflow_instance=workflow_instance,
        agent=AGENT_ID, proposal_type="welcome_message", client_id=record.client_id, subject_id=employee_id,
        payload=draft.model_dump(mode="json"), rationale="Draft welcome communication for HR review before send.",
        confidence=0.9, run_id=new_id("run")))
    audit.record("welcome.draft_submitted", agent=AGENT_ID, subject_id=employee_id, draft_id=draft.id,
                 approval_id=item.id, skill=NOTE_SKILL.ref)
    return draft, item


def apply_decision(port: OnboardingPort, audit: AuditLog, item: ApprovalItem) -> None:
    """HITLInbox decision -> CommunicationDraft status. Register via hitl.subscribe(...) so every
    decision (approve/edit/reject) made through the real approval mechanism is reflected in the
    onboarding repository; never a status the agent sets on its own say-so.
    """
    if item.agent != AGENT_ID or item.proposal_type != "welcome_message":
        return
    draft_id = item.payload["id"]
    status = {Decision.APPROVED: CommunicationStatus.APPROVED, Decision.EDITED: CommunicationStatus.APPROVED,
              Decision.REJECTED: CommunicationStatus.REJECTED}.get(item.status)
    if status is None:
        return
    if port.get_communication_draft(draft_id).status == CommunicationStatus.SENT:
        audit.record("welcome.late_decision_ignored", agent=AGENT_ID, subject_id=item.subject_id, draft_id=draft_id)
        return  # already delivered -- a replayed decision must never move it back to APPROVED
    port.update_communication_status(draft_id, status)
    audit.record("welcome.decision_applied", agent=AGENT_ID, subject_id=item.subject_id, draft_id=draft_id,
                 decision=item.status, reason_code=item.reason_code)
