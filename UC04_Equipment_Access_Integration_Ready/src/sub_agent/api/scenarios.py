# --------------------------------------------------------------------------------------------------------- derived views
def status_label(status: str) -> str:
    """Label of the Swagger example on the DEV ONLY status endpoint."""
    return f"DEV ONLY - set {status}"


def operation_tags(endpoint: str) -> list[str]:
    return [TAGS[t]["name"] for t in sorted({s.tag for s in SCENARIOS if s.endpoint == endpoint})]


def chain(scenario: Scenario) -> list[Scenario]:
    """The scenarios to run, in order, ending with `scenario`."""
    return (chain(BY_KEY[scenario.after]) if scenario.after else []) + [scenario]


def describe_expect(expect: dict[str, Any]) -> str:
    """The machine-checked expectation in words (used by the catalog)."""
    parts = []
    for key, value in expect.items():
        if key == "items":
            parts.append("item states " + ", ".join(f"{k}={v}" for k, v in value.items()))
        elif isinstance(value, list):
            parts.append(f"{key} = {', '.join(value) if value else 'none'}")
        else:
            parts.append(f"{key} = {value}")
    return "; ".join(parts)


def example_description(scenario: Scenario) -> str:
    from sub_agent.api.catalog import how_to_steps  # local import: catalog imports this module

    steps = " ".join(f"{i}. {s}" for i, s in enumerate(how_to_steps(scenario), 1))
    return (f"**Purpose:** {scenario.purpose}\n\n**Input fixture:** {scenario.fixture}\n\n**How to run:** {steps}\n\n"
            f"**Expected HTTP:** {scenario.http}\n\n**Expected result:** {scenario.result}\n\n**Inspect:** {scenario.inspect}")


def build_examples(endpoint: str) -> dict[str, dict[str, Any]]:
    return {s.key: {"summary": s.label, "description": example_description(s), "value": s.body}
            for s in SCENARIOS if s.endpoint == endpoint}
