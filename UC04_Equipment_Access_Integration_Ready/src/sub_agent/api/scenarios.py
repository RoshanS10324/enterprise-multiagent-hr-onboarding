@dataclass(frozen=True)
class Step:
    """A DEV ONLY preparation step run before a scenario."""

    kind: str  # "reset" | "status"
    case_id: str = ""
    status: str = ""


RESET = Step("reset")


@dataclass(frozen=True)
class Scenario:
    key: str
    tag: str
    title: str
    endpoint: str  # evaluate | submit | orchestrated
    purpose: str
    fixture: str
    result: str
    inspect: str
    body: dict[str, Any]
    http: int
    expect: dict[str, Any]
    prep: tuple[Step, ...] = ()
    after: str | None = None  # run this earlier scenario first, without resetting
    compare_with: str | None = None

    @property
    def number(self) -> str:
        return self.key.split("_", 1)[0]

    @property
    def outcome(self) -> str:
        e = self.expect
        return f"{self.http} {e.get('error') or e.get('overall') or e.get('api_status') or ''}".strip()

    @property
    def label(self) -> str:
        return f"{self.tag} | {self.title} -> {self.outcome}"


def _req(payload: dict, key: str, *, roles: list[str] | None = None, reset: bool = True) -> dict[str, Any]:
    return {"actor_id": CALLER_ID, "roles": list(roles or CALLER_ROLES), "idempotency_key": key, "dev_reset_first": reset,
            "input": payload}


def _orch(payload: dict, key: str, *, instance: str | None = None, roles: list[str] | None = None, reset: bool = True) -> dict:
    return {"contract_version": "1.0", "run_id": f"run-{key}", "idempotency_key": key, "dev_reset_first": reset,
            "workflow": {"id": "onboarding", "instance": instance or payload["case_id"], "step": "sub_agent"},
            "actor": {"on_behalf_of": CALLER_ID, "roles": list(roles or ["onboarding_orchestrator"])}, "input": payload}


SCENARIOS: list[Scenario] = []


def _add(key: str, title: str, endpoint: str, body: dict, http: int, expect: dict, *, purpose: str, fixture: str, result: str,
         inspect: str, prep: tuple[Step, ...] = (), after: str | None = None, compare_with: str | None = None) -> None:
    SCENARIOS.append(Scenario(key=key, tag=key.split("_", 1)[0], title=title, endpoint=endpoint, purpose=purpose, fixture=fixture,
                              result=result, inspect=inspect, body=body, http=http, expect=expect, prep=prep, after=after,
                              compare_with=compare_with))


